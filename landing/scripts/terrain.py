import math, sys
N = 44  # samples per ring

def ring(cx, cy, r, k, seed, sx=1.0, sy=1.0):
    pts = []
    for i in range(N):
        t = 2*math.pi*i/N
        g = 1 + (0.035+0.006*k)*math.sin(2*t+seed) + (0.028+0.005*k)*math.sin(3*t+1.7+seed*0.5) \
              + 0.018*math.sin(5*t+0.6+seed) + 0.010*math.sin(7*t+2.1)
        rr = r*g
        pts.append((cx + rr*math.cos(t)*sx, cy + rr*math.sin(t)*sy))
    return pts

def cr_path(pts, closed=True, prec=0):
    # Catmull-Rom -> cubic bezier
    n = len(pts)
    f = lambda v: (lambda t: t.rstrip('0').rstrip('.') if '.' in t else t)(f"{v:.{prec}f}")
    d = f"M{f(pts[0][0])} {f(pts[0][1])}"
    rng = range(n) if closed else range(n-1)
    for i in rng:
        p0 = pts[(i-1) % n] if closed else pts[max(i-1,0)]
        p1 = pts[i]; p2 = pts[(i+1) % n] if closed else pts[i+1]
        p3 = pts[(i+2) % n] if closed else pts[min(i+2,n-1)]
        c1 = (p1[0]+(p2[0]-p0[0])/6, p1[1]+(p2[1]-p0[1])/6)
        c2 = (p2[0]-(p3[0]-p1[0])/6, p2[1]-(p3[1]-p1[1])/6)
        d += f"C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(p2[0])} {f(p2[1])}"
    return d + ("Z" if closed else "")

def inside(p, poly):
    x,y=p; c=False; n=len(poly)
    for i in range(n):
        x1,y1=poly[i]; x2,y2=poly[(i+1)%n]
        if (y1>y)!=(y2>y) and x < (x2-x1)*(y-y1)/(y2-y1)+x1: c=not c
    return c

def mind(a,b): return min(math.dist(p,q) for p in a for q in b)

summit=(560,232)
main=[]
for k in range(8):
    cx = summit[0] - k*15; cy = summit[1] + k*17
    main.append(ring(cx, cy, 20 + k*39, k, 0.4, 1.16, 1.0))
hill=[ring(92,104, 18+k*24, k, 2.3, 1.1, 0.92) for k in range(3)]
ok=True
for a,b in zip(main, main[1:]):
    if not all(inside(p,b) for p in a): ok=False; print("main nest fail", file=sys.stderr)
    print("main gap", round(mind(a,b),1), file=sys.stderr)
for a,b in zip(hill, hill[1:]):
    if not all(inside(p,b) for p in a): ok=False
print("hill<->main gap", round(mind(hill[-1], main[-1]),1), round(mind(hill[-1], main[-2]),1), file=sys.stderr)
if any(inside(p, main[-1]) for p in hill[-1]): print("hill overlaps main outer (ok if clipped)", file=sys.stderr)

route_pts=[(96,720),(176,646),(268,612),(338,548),(312,478),(392,428),(466,372),(448,316),(508,272),(560,236)]
L=sum(math.dist(a,b) for a,b in zip(route_pts,route_pts[1:]))
print("nested ok", ok, "route approx len", round(L), file=sys.stderr)

def label(k):
    pts = main[k]; i = 40  # just above due east on the ring
    (x0,y0),(x1,y1) = pts[i-1], pts[(i+1) % N]
    x,y = pts[i]; a = math.degrees(math.atan2(y1-y0, x1-x0))
    if a > 90: a -= 180
    if a < -90: a += 180
    return f"  {{ x: {x:.1f}, y: {y:.1f}, angle: {a:.1f}, text: 'L{k+1}' }},"

out=["// Generated by scripts/terrain.py. Contour rings for the hero survey map (viewBox 0 0 800 760).",
     "// Rings are listed summit-outward; each is verified to nest inside the next.",
     "export const MAIN_CONTOURS = ["] + [f"  '{cr_path(r)}'," for r in main] + ["] as const", "",
     "export const HILL_CONTOURS = ["] + [f"  '{cr_path(r)}'," for r in hill] + ["] as const", "",
     f"export const ROUTE = '{cr_path(route_pts, closed=False)}'", "",
     "export const SUMMIT = { x: 560, y: 232 } as const", "",
     "// On-ring anchor points (x, y, tangent angle in degrees) for contour height labels.",
     "export const CONTOUR_LABELS = ["] + [label(k) for k in (2, 4, 6)] + ["] as const"]
open(sys.argv[1],'w').write("\n".join(out)+"\n")
